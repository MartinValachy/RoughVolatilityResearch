#!/usr/bin/env python3
"""Build INDEX.md: a compact locator map (file -> headings/defs/columns with line numbers).
Never opens data/sealed, data/raw, data/derived contents, PDFs, .venv, runs, results, tmp. Stdlib only."""
import os, sys, json, re
root = sys.argv[1] if len(sys.argv) > 1 else "."
SKIP_DIRS = {".git", ".venv", "venv", "__pycache__", "node_modules", "tmp", "runs", "results", ".pytest_cache", ".ipynb_checkpoints"}
NO_OPEN = {"data/sealed", "data/raw", "data/derived", "literature"}   # list names/sizes only
MAXH, MAXD = 25, 30
out = ["# INDEX.md (auto-generated by scripts/build_index.py; do not edit; rebuild after adding files)",
       "Use: find the file/line here, then `sed -n a,bp FILE` only that range. Format: path (lines, KB) then L<line>: item.\n"]
def rel(p): return os.path.relpath(p, root).replace("\\", "/")
def lines_of(p):
    try:
        with open(p, "r", encoding="utf-8", errors="replace") as f: return f.read().splitlines()
    except Exception: return []
for d, dirs, files in os.walk(root):
    dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
    r = rel(d)
    if any(r == n or r.startswith(n + "/") for n in NO_OPEN):
        n = len(files)
        if n: out.append(f"[{r}/] {n} files (names/sizes only; contents not indexed)")
        continue
    for fn in sorted(files):
        p = os.path.join(d, fn); ext = os.path.splitext(fn)[1].lower(); kb = os.path.getsize(p) / 1024
        if ext in (".md", ".txt", ".tex"):
            L = lines_of(p); items = [f"L{i+1}: {l.strip()[:80]}" for i, l in enumerate(L) if re.match(r"^(#{1,3} |\\(sub)*section)", l)][:MAXH]
        elif ext == ".py":
            L = lines_of(p); items = [f"L{i+1}: {l.strip()[:80]}" for i, l in enumerate(L) if re.match(r"^\s{0,4}(def|class) ", l)][:MAXD]
        elif ext in (".csv", ".tsv"):
            L = lines_of(p)[:1]; items = ["cols: " + (L[0][:200] if L else "")]
        elif ext == ".json":
            try:
                j = json.load(open(p, encoding="utf-8")); items = ["keys: " + ", ".join(list(j)[:20])] if isinstance(j, dict) else [f"list[{len(j)}]"]
            except Exception: items = []
        elif ext in (".yaml", ".yml", ".toml"): items = []
        else: continue
        nl = sum(1 for _ in open(p, "rb")) if kb < 2048 else -1
        out.append(f"{rel(p)} ({nl} lines, {kb:.0f} KB)")
        out += ["  " + i for i in items]
open(os.path.join(root, "INDEX.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"INDEX.md written: {len(out)} lines")
